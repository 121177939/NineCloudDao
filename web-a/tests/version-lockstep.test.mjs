import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const release=JSON.parse(readFileSync(new URL('../../VERSION.json',import.meta.url),'utf8'));
const html=readFileSync(new URL('../site/index.html',import.meta.url),'utf8');
assert.match(release.versionName,/^\d+\.\d+\.\d+(?:\.\d+)?$/);
assert.ok(Number.isInteger(release.versionCode)&&release.versionCode>0);
assert.ok(html.includes(`<title>控制中心 · WAP ${release.versionName}</title>`));
assert.ok(html.includes(`>WAP ${release.versionName}</span>`));
assert.ok(html.includes(`app.js?v=${release.versionName}`));
assert.ok(html.includes(`parser.js?v=${release.versionName}`));
assert.doesNotMatch(html,/WAP (?:1[0-7]|阶段)/);
console.log(`PASS WAP version ${release.versionName} / ${release.versionCode}`);
