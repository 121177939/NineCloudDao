import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const version=JSON.parse(readFileSync(new URL('../../VERSION.json',import.meta.url),'utf8'));
const html=readFileSync(new URL('../site/index.html',import.meta.url),'utf8');
assert.equal(version.versionName,'2.0.61.1');
assert.equal(version.versionCode,116);
assert.match(html,/<title>控制中心 · WAP 2\.0\.61\.1<\/title>/);
assert.match(html,/>WAP 2\.0\.61\.1<\/span>/);
assert.match(html,/app\.js\?v=2\.0\.61\.1/);
assert.match(html,/parser\.js\?v=2\.0\.61\.1/);
assert.doesNotMatch(html,/WAP (?:1[0-7]|阶段)/);
console.log('PASS current WAP display version 2.0.61.1');
