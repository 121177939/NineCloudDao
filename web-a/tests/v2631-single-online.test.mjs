import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {presenceState,HEARTBEAT_DISPLAY_GRACE_MS} from '../site/presence-display.js';
const clock=Date.parse('2026-11-05T12:00:00Z');
const p=(state,age,extra={})=>presenceState({serverTime:clock,row:{state,seen_at:new Date(clock-age).toISOString(),...extra}});
assert.equal(HEARTBEAT_DISPLAY_GRACE_MS,30_000);
assert.match(p('busy',1000,{completed_items:0,total_items:1}).text,/B 在线 · 正在执行 · 0\/1组/);
assert.match(p('idle',1000).text,/B 在线 · 空闲待命/);
assert.match(p('idle',12001).text,/B 在线/,'12s send safety threshold must NOT flash UI offline');
assert.match(p('busy',29999).text,/B 在线/,'brief jitter does not flap');
assert.match(p('busy',30001).text,/B 离线/);
assert.match(p('paused',1000).text,/B 在线 · 暂停接单/);
assert.match(p('attention',1000,{stage:'全局控制状态暂不可核实'}).text,/B 在线 · 控制连接核验中/);
assert.match(p('busy',1000,{stage:'核查任务'}).text,/核查任务/);
assert.match(p('busy',1000,{seen_at:'invalid'}).text,/暂时无法核实/);
assert.match(p('idle',1000,{state:'bogus'}).text,/暂时无法核实/);
assert.match(p('idle',1000,{seen_at:'invalid'}).text,/暂时无法核实/);
assert.match(p('idle',1000,{seen_at:'2026-11-05T12:00:20Z'}).text,/暂时无法核实/);
assert.match(presenceState({row:null}).text,/B 离线/);
const app=readFileSync(new URL('../site/app.js',import.meta.url),'utf8');
assert.doesNotMatch(app,/B Realtime 未确认|B Realtime 离线|B 实时在线/);
assert.match(app,/\$\('b-status'\)\.textContent=display\.text/);
assert.doesNotMatch(app,/正在刷新执行端状态/);
console.log('PASS v2.0.63.1 B online indicator derives only from server heartbeat');
