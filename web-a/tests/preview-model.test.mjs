import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createPreviewModel,exampleSuite,normalizeForOffsets} from '../site/preview-model.js';
const ctx={};vm.runInNewContext(fs.readFileSync(new URL('../site/parser.js',import.meta.url),'utf8'),ctx);
const p=ctx.parser.com.example.remotea.WebParser;
let passed=0;
function check(condition,msg){assert.ok(condition,msg);passed++;}
const long='5000..5157..8157...5638..8638..5303..8303, 8182..0182, 4323, 3712, 5155..7197, , 5290, , 8782....1503五七各1';
const data=JSON.parse(p.inspect(long));
const model=createPreviewModel(long,data);
check(data.valid,'valid source recognition');
check(model.scatterCount===16,'16 independent wager items preserved');
check(model.totalCount===16,'header/tab counts remain 16');
check(model.scatterOriginal.startsWith('5000，5157，8157'),'source order retained');
check(model.scatterOriginal.endsWith('1503'),'source tail retained');
check(model.scatterRecognition==='5000、5157、8157、5638、8638、5303、8303、8182、0182、4323、3712、5155、7197、5290、8782、1503各1元','monetary grouping');
check(model.ignored.map(x=>x.source).join('、')==='五七','ignored titles tracked separately');
check(model.scatter.every(x=>x.matched),'each authoritative code mapped');
check(model.suiteCount===0,'no suite');
check(model.turnCount===0,'no fullturn');
check(data.totalJiao===160,'original monetary total unchanged');
const suiteStr='1234-1234各1',suite=createPreviewModel(suiteStr,JSON.parse(p.inspect(suiteStr)));
check(suite.scatterCount===0,'pure suite has no scatter');
check(suite.suiteCount===1 && suite.suites[0].expectedCount===16,'suite 16 choices retained');
check(suite.suites[0].source===suiteStr,'original suite source visible');
check(suite.suites[0].examples.length===16,'suite expansion has 16 samples');
const turn=createPreviewModel('1234全转各1',JSON.parse(p.inspect('1234全转各1')));
check(turn.scatterCount===0&&turn.turnCount===1,'fullturn not added to ordinary scatter');
check(turn.totalCount===1,'fullturn counted once');
const mixed=createPreviewModel('1234各1元，12头34尾各1元',JSON.parse(p.inspect('1234各1元，12头34尾各1元')));
check(mixed.scatterCount===1&&mixed.suiteCount===1,'mixed preserves both sections');
check(normalizeForOffsets(long).length===long.length,'mapping retains text offsets');
check(exampleSuite('123头123百123十123尾=1',30).length===30,'suite samples capped');
console.log('PASS: '+passed+' preview equivalence checks');
